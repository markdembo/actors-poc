#!/usr/bin/env node
// Reproducible static comparison: Actors abstraction vs raw Durable Objects, same app.
// Counts non-blank, non-comment lines the developer writes, and which Durable Objects
// concepts appear in their code. Run: node comparison/measure.mjs [--json]
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const implementations = {
  "Actors (examples/agent)": {
    app: ["examples/agent/src/actors/support-agent.ts", "examples/agent/src/index.ts"],
    // wrangler.jsonc is generated by `actors generate`; the developer authors none of it.
    config: [],
    generated: ["examples/agent/wrangler.jsonc"],
  },
  "Raw Durable Objects (comparison/raw-do-agent)": {
    app: ["comparison/raw-do-agent/src/agent.ts", "comparison/raw-do-agent/src/index.ts"],
    config: ["comparison/raw-do-agent/wrangler.jsonc"],
    generated: [],
  },
};

// Platform-specific concepts a developer must understand to write the code.
const CONCEPTS = [
  ["DurableObject base class", /extends\s+DurableObject\b/],
  ["Namespace binding type", /DurableObjectNamespace\b/],
  ["Env interface for bindings", /interface\s+Env\b/],
  ["Object identity (idFromName/getByName)", /\b(idFromName|getByName|newUniqueId)\b/],
  ["Stubs", /\.get\(\s*env\.|\bstub\b/],
  ["Exporting the class from the Worker entry", /export\s*\{[^}]*\b[A-Z]\w+\b[^}]*\}\s*;?\s*$|export\s*\{\s*SupportAgent/m],
  ["blockConcurrencyWhile / input gates", /blockConcurrencyWhile/],
  ["Storage API (ctx.storage)", /ctx\.storage\b/],
  ["SQL storage API", /storage\.sql|sql\.exec/],
  ["Alarms (setAlarm/alarm())", /setAlarm|getAlarm|\balarm\(\)/],
  ["Hand-rolled serialization queue", /this\.queue\b/],
  ["Hand-rolled copy-then-commit", /structuredClone\(/],
  ["Passing identity into the object", /customerId:\s*string,\s*\w+:/],
  ["Durable Object bindings config", /"durable_objects"/],
  ["Migrations config", /"migrations"/],
];

function codeLines(file) {
  const p = join(root, file);
  if (!existsSync(p)) return { lines: 0, text: "" };
  const text = readFileSync(p, "utf8");
  let inBlock = false;
  let lines = 0;
  for (const raw of text.split("\n")) {
    let line = raw.trim();
    if (inBlock) {
      if (line.includes("*/")) {
        inBlock = false;
        line = line.slice(line.indexOf("*/") + 2).trim();
      } else continue;
    }
    if (line.startsWith("/*")) {
      if (!line.includes("*/")) inBlock = true;
      continue;
    }
    if (!line || line.startsWith("//")) continue;
    lines++;
  }
  return { lines, text };
}

const results = {};
for (const [name, impl] of Object.entries(implementations)) {
  const app = impl.app.map(codeLines);
  const config = impl.config.map(codeLines);
  const all = [...app, ...config].map((x) => x.text).join("\n");
  results[name] = {
    appLines: app.reduce((n, x) => n + x.lines, 0),
    configLines: config.reduce((n, x) => n + x.lines, 0),
    concepts: CONCEPTS.filter(([, re]) => re.test(all)).map(([c]) => c),
    files: [...impl.app, ...impl.config],
  };
}

if (process.argv.includes("--json")) {
  console.log(JSON.stringify(results, null, 2));
} else {
  const [a, r] = Object.values(results);
  const [an, rn] = Object.keys(results);
  const pct = (x, y) => (y === 0 ? "n/a" : `${Math.round((1 - x / y) * 100)}%`);
  console.log("Same app: per-customer support agent (chat, memory, tasks, reminders, rollback on model failure)\n");
  console.log(`${"".padEnd(34)}${"Actors".padStart(10)}${"Raw DO".padStart(10)}${"Reduction".padStart(12)}`);
  const row = (label, x, y) => console.log(`${label.padEnd(34)}${String(x).padStart(10)}${String(y).padStart(10)}${pct(x, y).padStart(12)}`);
  row("Application code (lines)", a.appLines, r.appLines);
  row("Hand-written config (lines)", a.configLines, r.configLines);
  row("Total developer-authored lines", a.appLines + a.configLines, r.appLines + r.configLines);
  row("Durable Objects concepts used", a.concepts.length, r.concepts.length);
  console.log(`\nDO concepts in ${rn}:\n  - ${r.concepts.join("\n  - ")}`);
  console.log(`\nDO concepts in ${an}:\n  ${a.concepts.length ? `- ${a.concepts.join("\n  - ")}` : "(none)"}`);
  console.log("\nLines exclude blanks and comments. The shared simulated model (examples/agent/src/model.ts) is excluded from both.");
}
